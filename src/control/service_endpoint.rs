//! Per-execution publication owned by the scheduled shell collector.
use super::{Control, schedule::service_not_found, storage_error};
use crate::protocol::{ApiError, ErrorCode, ServiceEndpoint, ServiceEndpointArgs};
use rusqlite::OptionalExtension;
use std::{
    collections::HashMap,
    fs::OpenOptions,
    io::Read,
    path::{Path, PathBuf},
    sync::{Arc, Mutex},
    time::Duration,
};

pub(super) const ENV: &str = "SHELLBOY_SERVICE_ENDPOINT_FILE";
const MAX_BYTES: u64 = 8192;

fn path(data: &Path, instance: &str, execution: &str) -> PathBuf {
    data.join(format!("service-endpoint-{instance}-{execution}.json"))
}

pub(super) struct Publication(PathBuf);

impl Publication {
    pub(super) fn create(control: &Control, execution: &str) -> Result<Self, ApiError> {
        let file = path(&control.data_dir, &control.store.instance_id, execution);
        if file.to_str().is_none() {
            return Err(ApiError::new(
                ErrorCode::IoFailed,
                "Service endpoint path is not UTF-8",
            ));
        }
        crate::atomic_file::create_private_required(&file).map_err(|_| {
            ApiError::new(ErrorCode::IoFailed, "Cannot create service endpoint file")
        })?;
        Ok(Self(file))
    }

    pub(super) fn env_value(&self) -> String {
        self.0.to_str().expect("validated endpoint path").to_owned()
    }
}

impl Drop for Publication {
    fn drop(&mut self) {
        if let Err(error) = std::fs::remove_file(&self.0)
            && error.kind() != std::io::ErrorKind::NotFound
        {
            eprintln!("Could not remove service endpoint runtime file");
        }
    }
}

/// Revocations and successful reads are ordered at this short, in-memory
/// boundary. A stop holds it through the DB commit; no filesystem I/O under it.
#[derive(Default)]
pub(super) struct Publications(Mutex<HashMap<String, PathBuf>>);

impl Publications {
    pub(super) fn register(&self, id: &str, publication: &Publication) {
        self.0
            .lock()
            .unwrap()
            .insert(id.into(), publication.0.clone());
    }

    pub(super) fn revoke(&self, id: &str) {
        self.0.lock().unwrap().remove(id);
    }

    pub(super) fn commit_revoke<'a>(
        &self,
        tx: rusqlite::Transaction<'_>,
        ids: impl IntoIterator<Item = &'a str>,
    ) -> rusqlite::Result<()> {
        let mut live = self.0.lock().unwrap();
        tx.commit()?;
        for id in ids {
            live.remove(id);
        }
        Ok(())
    }

    fn settle<T>(&self, id: &str, path: &Path, result: Result<T, ApiError>) -> Result<T, ApiError> {
        let live = self.0.lock().unwrap();
        if live.get(id).is_some_and(|current| current == path) {
            result
        } else {
            Err(unavailable("service_not_running"))
        }
    }
}

/// Called under the exclusive data owner lock, before starting any new work.
/// Only names generated by the publication owner are retired.
pub(crate) fn recover(data: &Path) -> std::io::Result<()> {
    for entry in std::fs::read_dir(data)? {
        let entry = entry?;
        let name = entry.file_name();
        let Some(key) = name
            .to_str()
            .and_then(|s| s.strip_prefix("service-endpoint-"))
            .and_then(|s| s.strip_suffix(".json"))
        else {
            continue;
        };
        if key.len() != 73
            || key.as_bytes()[36] != b'-'
            || !key
                .get(..36)
                .is_some_and(|s| uuid::Uuid::parse_str(s).is_ok())
            || !key
                .get(37..)
                .is_some_and(|s| uuid::Uuid::parse_str(s).is_ok())
        {
            continue;
        }
        if !entry.file_type()?.is_dir() {
            match std::fs::remove_file(entry.path()) {
                Ok(()) => {}
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                Err(error) => return Err(error),
            }
        }
    }
    Ok(())
}

fn unavailable(reason: &'static str) -> ApiError {
    ApiError::new(ErrorCode::InvalidState, "Service endpoint is unavailable")
        .details(serde_json::json!({"reason":reason}))
}

async fn running(control: &Control, args: ServiceEndpointArgs) -> Result<String, ApiError> {
    let row = control.store.database.call(move |db| {
        let selector = if args.service_id.is_some() { "q.id=?1" } else { "q.thread_id=?1 AND q.name=?2" };
        let sql = format!("SELECT CASE WHEN q.enabled AND s.state='running' THEN s.id END
             FROM schedule q JOIN thread t ON t.id=q.thread_id AND t.deleted_at IS NULL
             LEFT JOIN shell_execution s ON s.id=(SELECT id FROM shell_execution INDEXED BY shell_active_schedule WHERE schedule_id=q.id AND state IN ('starting','running','stopping') ORDER BY rowid DESC LIMIT 1)
             WHERE {selector} AND q.kind='service'");
        let key = args.service_id.as_deref().or(args.thread_id.as_deref());
        let parameters = [key, args.name.as_deref()];
        let count = if args.service_id.is_some() { 1 } else { 2 };
        Ok(db.query_row(&sql, rusqlite::params_from_iter(&parameters[..count]), |row| row.get::<_, Option<String>>(0)).optional()?)
    }).await.map_err(storage_error)?;
    row.ok_or_else(service_not_found)?
        .ok_or_else(|| unavailable("service_not_running"))
}

pub(super) async fn read(
    control: &Control,
    args: ServiceEndpointArgs,
) -> Result<ServiceEndpoint, ApiError> {
    let execution = running(control, args).await?;
    let registry = Arc::clone(&control.publications);
    let file = registry
        .0
        .lock()
        .unwrap()
        .get(&execution)
        .cloned()
        .ok_or_else(|| unavailable("service_not_running"))?;
    let read_path = file.clone();
    let deadline = tokio::time::Instant::now()
        + Duration::from_millis(control.store.config.io.file_prepare_timeout_ms);
    let value = control
        .attachments
        .workers
        .execute(deadline, control.stop.child_token(), move || {
            read_file(&read_path)
        })
        .await
        .map_err(|_| unavailable("service_endpoint_unavailable"));
    registry.settle(&execution, &file, value)
}

fn read_file(path: &Path) -> Result<ServiceEndpoint, ApiError> {
    let invalid = || unavailable("service_endpoint_unavailable");
    let mut options = OpenOptions::new();
    options.read(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK);
    }
    #[cfg(windows)]
    {
        use std::os::windows::fs::OpenOptionsExt;
        options.custom_flags(windows_sys::Win32::Storage::FileSystem::FILE_FLAG_OPEN_REPARSE_POINT);
    }
    let file = options.open(path).map_err(|_| invalid())?;
    let metadata = file.metadata().map_err(|_| invalid())?;
    if !metadata.is_file() {
        return Err(invalid());
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::MetadataExt;
        if metadata.uid() != unsafe { libc::geteuid() }
            || metadata.mode() & 0o077 != 0
            || metadata.nlink() != 1
        {
            return Err(invalid());
        }
    }
    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt;
        if metadata.file_attributes()
            & windows_sys::Win32::Storage::FileSystem::FILE_ATTRIBUTE_REPARSE_POINT
            != 0
            || !matches!(crate::atomic_file::has_private_acl(&file), Ok(true))
        {
            return Err(invalid());
        }
    }
    let mut body = Vec::new();
    file.take(MAX_BYTES + 1)
        .read_to_end(&mut body)
        .map_err(|_| invalid())?;
    if body.len() as u64 > MAX_BYTES {
        return Err(invalid());
    }
    let endpoint: ServiceEndpoint = serde_json::from_slice(&body).map_err(|_| invalid())?;
    if endpoint.port == 0
        || endpoint.token.is_empty()
        || !endpoint.token.bytes().all(|b| b.is_ascii_graphic())
    {
        return Err(invalid());
    }
    Ok(endpoint)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stop_commit_revokes_only_the_exact_publication_before_settlement() {
        let dir = tempfile::tempdir().unwrap();
        let pending = Publication(dir.path().join("pending"));
        let live = Publication(dir.path().join("live"));
        let publications = Publications::default();
        publications.register("retiring", &pending);
        publications.register("other", &live);
        assert_eq!(
            publications.settle("retiring", &pending.0, Ok(5)).unwrap(),
            5
        );
        let mut db = rusqlite::Connection::open_in_memory().unwrap();
        publications
            .commit_revoke(db.transaction().unwrap(), ["retiring"])
            .unwrap();
        assert_eq!(
            publications
                .settle("retiring", &pending.0, Ok(5))
                .unwrap_err()
                .details
                .unwrap()["reason"],
            "service_not_running"
        );
        assert_eq!(publications.settle("other", &live.0, Ok(6)).unwrap(), 6);
    }
}
